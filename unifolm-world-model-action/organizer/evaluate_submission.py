#!/usr/bin/env python3
"""Clone, launch and externally score one UnifoLM-WMA competition submission.

Run this only inside the organizer's sealed judge container.  The program does
not sandbox arbitrary submission code; --execute is deliberately opt-in.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import signal
import subprocess
import sys
import time
from typing import Any


def require_path(path: Path, description: str, *, directory: bool) -> Path:
    resolved = path.resolve()
    valid = resolved.is_dir() if directory else resolved.is_file()
    if not valid:
        kind = "directory" if directory else "file"
        raise ValueError(f"{description} must be an existing {kind}: {path}")
    return resolved


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source_file:
        for chunk in iter(lambda: source_file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_cases(case_dir: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    manifest_path = case_dir / "manifest.json"
    with manifest_path.open("r", encoding="utf-8") as manifest_file:
        manifest = json.load(manifest_file)

    samples = manifest.get("samples")
    model_config = manifest.get("model_config")
    if not isinstance(samples, list) or not samples or not isinstance(model_config, dict):
        raise ValueError("private manifest must contain non-empty samples and model_config")

    required_model_keys = {"height", "width", "video_length", "ddim_steps", "ddim_eta"}
    missing_model_keys = required_model_keys.difference(model_config)
    if missing_model_keys:
        raise ValueError(f"manifest model_config missing: {sorted(missing_model_keys)}")

    for sample in samples:
        required_sample_keys = {"dataset", "frame_stride", "original_n_iter"}
        missing_sample_keys = required_sample_keys.difference(sample)
        if missing_sample_keys:
            raise ValueError(f"manifest sample missing: {sorted(missing_sample_keys)}")
        cache_path = case_dir / "preprocessed_inputs" / (
            f"{sample['dataset']}-fs{sample['frame_stride']}.pt")
        if not cache_path.is_file():
            raise ValueError(f"private cache is missing: {cache_path}")
    return manifest, samples


def judge_launcher(manifest: dict[str, Any], samples: list[dict[str, Any]]) -> str:
    """Create the launcher copied into a submission after its checkout.

    Values are embedded by the organizer.  The submission cannot select a
    shorter trajectory by setting environment variables or editing its own
    public launcher.
    """
    model_config = manifest["model_config"]
    seed = int(manifest.get("seed", 123))
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Generated by the organizer. Do not use participant timing output.",
        'case_dir="${JUDGE_CASE_DIR:?JUDGE_CASE_DIR is required}"',
        'checkpoint="${JUDGE_CHECKPOINT:?JUDGE_CHECKPOINT is required}"',
        'result_dir="${JUDGE_RESULT_DIR:?JUDGE_RESULT_DIR is required}"',
        f"export PYTHONHASHSEED={seed}",
        'export CUBLAS_WORKSPACE_CONFIG="${CUBLAS_WORKSPACE_CONFIG:-:4096:8}"',
        "export TOKENIZERS_PARALLELISM=false",
        'export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}"',
        'export PYTHONPATH="$PWD/src${PYTHONPATH:+:$PYTHONPATH}"',
        'mkdir -p "${result_dir}"',
        "",
    ]
    for sample in samples:
        dataset = shlex.quote(str(sample["dataset"]))
        stride = int(sample["frame_stride"])
        n_iter = int(sample["original_n_iter"])
        lines.extend([
            "python3 scripts/evaluation/world_model_interaction.py \\",
            f"    --seed {seed} \\",
            '    --ckpt_path "${checkpoint}" \\',
            "    --config configs/inference/world_model_interaction.yaml \\",
            f"    --dataset {dataset} \\",
            f'    --savedir "${{result_dir}}"/{dataset} \\',
            f"    --bs 1 --height {int(model_config['height'])} --width {int(model_config['width'])} \\",
            "    --unconditional_guidance_scale 1.0 \\",
            f"    --ddim_steps {int(model_config['ddim_steps'])} --ddim_eta {float(model_config['ddim_eta'])} \\",
            f"    --video_length {int(model_config['video_length'])} --frame_stride {stride} \\",
            f"    --exe_steps 16 --n_iter {n_iter} \\",
            "    --timestep_spacing uniform_trailing --guidance_rescale 0.7 \\",
            "    --perframe_ae \\",
            '    --input_cache_dir "${case_dir}/preprocessed_inputs" --require_input_cache',
            "",
        ])
    return "\n".join(lines) + "\n"


def clone_submission(repo: str, revision: str, work_dir: Path) -> None:
    if work_dir.exists():
        raise ValueError(f"work directory already exists: {work_dir}")
    subprocess.run(["git", "clone", "--no-tags", repo, str(work_dir)], check=True)
    subprocess.run(["git", "-C", str(work_dir), "checkout", "--detach", revision], check=True)


def controlled_environment(submission_dir: Path, case_dir: Path,
                           checkpoint: Path, result_dir: Path,
                           cuda_visible_devices: str) -> dict[str, str]:
    """Provide only the runtime variables needed by the fixed launcher."""
    environment = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        "HOME": str(submission_dir / ".judge_home"),
        "PYTHONHASHSEED": "123",
        "CUBLAS_WORKSPACE_CONFIG": ":4096:8",
        "TOKENIZERS_PARALLELISM": "false",
        "CUDA_VISIBLE_DEVICES": cuda_visible_devices,
        "JUDGE_CASE_DIR": str(case_dir),
        "JUDGE_CHECKPOINT": str(checkpoint),
        "JUDGE_RESULT_DIR": str(result_dir),
        "PYTHONPATH": str(submission_dir / "src"),
    }
    # CUDA libraries are normally supplied by the locked judge image.
    if "LD_LIBRARY_PATH" in os.environ:
        environment["LD_LIBRARY_PATH"] = os.environ["LD_LIBRARY_PATH"]
    Path(environment["HOME"]).mkdir(parents=True, exist_ok=True)
    return environment


def run_submission(command: list[str], cwd: Path, environment: dict[str, str],
                   timeout_s: float, log_path: Path) -> tuple[int, float, bool]:
    """Measure the child process externally and kill its complete process group."""
    started = time.perf_counter_ns()
    timed_out = False
    with log_path.open("w", encoding="utf-8") as log_file:
        process = subprocess.Popen(
            command,
            cwd=cwd,
            env=environment,
            stdout=log_file,
            stderr=subprocess.STDOUT,
            start_new_session=True,
            text=True,
        )
        try:
            exit_code = process.wait(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            timed_out = True
            os.killpg(process.pid, signal.SIGKILL)
            exit_code = process.wait()
        else:
            # A shell can exit while descendants it placed in the same process
            # group continue running. Remove them before output validation or
            # the next submission can observe their GPU/filesystem activity.
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    elapsed_s = (time.perf_counter_ns() - started) / 1_000_000_000
    return exit_code, elapsed_s, timed_out


def collect_videos(root: Path) -> dict[str, Path]:
    if not root.is_dir():
        raise ValueError(f"result directory was not created: {root}")
    videos: dict[str, Path] = {}
    for path in root.rglob("*.mp4"):
        if path.is_symlink():
            raise ValueError(f"result video must not be a symlink: {path}")
        videos[str(path.relative_to(root))] = path
    if not videos:
        raise ValueError(f"no MP4 results found under: {root}")
    return videos


def validate_videos(result_dir: Path, reference_dir: Path,
                    max_frame_mae: float, max_frame_error: int) -> dict[str, Any]:
    """Compare decoded pixels, never MP4 bytes or participant-reported hashes."""
    try:
        import torch
        from torchvision.io import read_video
    except ImportError as error:
        raise RuntimeError("judge image requires torch and torchvision video I/O") from error

    actual = collect_videos(result_dir)
    reference = collect_videos(reference_dir)
    if set(actual) != set(reference):
        missing = sorted(set(reference).difference(actual))
        extra = sorted(set(actual).difference(reference))
        raise ValueError(f"video set mismatch; missing={missing}, extra={extra}")

    per_video: dict[str, dict[str, float | int]] = {}
    worst_mae = 0.0
    worst_error = 0
    for relative_path in sorted(reference):
        actual_frames, _, _ = read_video(str(actual[relative_path]), pts_unit="sec")
        reference_frames, _, _ = read_video(str(reference[relative_path]), pts_unit="sec")
        if actual_frames.shape != reference_frames.shape:
            raise ValueError(
                f"frame shape mismatch for {relative_path}: "
                f"{tuple(actual_frames.shape)} != {tuple(reference_frames.shape)}")
        difference = (actual_frames.to(torch.int16) - reference_frames.to(torch.int16)).abs()
        mae = float(difference.float().mean().item())
        maximum = int(difference.max().item()) if difference.numel() else 0
        per_video[relative_path] = {"mae": mae, "max_error": maximum}
        worst_mae = max(worst_mae, mae)
        worst_error = max(worst_error, maximum)
        if mae > max_frame_mae or maximum > max_frame_error:
            raise ValueError(
                f"output differs for {relative_path}: mae={mae}, max_error={maximum}")

    return {
        "video_count": len(actual),
        "worst_frame_mae": worst_mae,
        "worst_frame_error": worst_error,
        "per_video": per_video,
    }


def parser() -> argparse.ArgumentParser:
    argument_parser = argparse.ArgumentParser(
        description="Private, external evaluator for one GitHub submission.")
    argument_parser.add_argument("--repo", required=True, help="Git URL or local Git repository")
    argument_parser.add_argument("--revision", required=True, help="Immutable commit SHA")
    argument_parser.add_argument("--case-dir", required=True, type=Path,
                                 help="Private directory with manifest.json and caches")
    argument_parser.add_argument("--reference-dir", required=True, type=Path,
                                 help="Private baseline result tree")
    argument_parser.add_argument("--checkpoint", required=True, type=Path,
                                 help="Read-only official checkpoint")
    argument_parser.add_argument("--work-dir", required=True, type=Path,
                                 help="New temporary submission checkout")
    argument_parser.add_argument("--log-dir", required=True, type=Path,
                                 help="Judge-owned output directory")
    argument_parser.add_argument("--timeout-s", type=float, default=7200.0)
    argument_parser.add_argument("--cuda-visible-devices", default="0")
    argument_parser.add_argument("--max-frame-mae", type=float, default=0.0)
    argument_parser.add_argument("--max-frame-error", type=int, default=0)
    argument_parser.add_argument("--execute", action="store_true",
                                 help="Actually execute untrusted code; requires a sealed judge container")
    return argument_parser


def main() -> int:
    args = parser().parse_args()
    if args.timeout_s <= 0:
        raise ValueError("--timeout-s must be positive")
    if args.max_frame_mae < 0 or args.max_frame_error < 0:
        raise ValueError("validation tolerances must be non-negative")

    case_dir = require_path(args.case_dir, "case directory", directory=True)
    reference_dir = require_path(args.reference_dir, "reference directory", directory=True)
    checkpoint = require_path(args.checkpoint, "checkpoint", directory=False)
    manifest, samples = load_cases(case_dir)
    expected_checkpoint_sha = manifest.get("checkpoint", {}).get("sha256")
    actual_checkpoint_sha = sha256_file(checkpoint)
    if expected_checkpoint_sha and actual_checkpoint_sha != expected_checkpoint_sha:
        raise ValueError(
            "checkpoint SHA-256 does not match the private manifest: "
            f"{actual_checkpoint_sha} != {expected_checkpoint_sha}")

    work_dir = args.work_dir.resolve()
    log_dir = args.log_dir.resolve()
    log_dir.mkdir(parents=True, exist_ok=True)
    clone_submission(args.repo, args.revision, work_dir)

    launcher_path = work_dir / "scripts" / "run_compute_benchmark.sh"
    if not launcher_path.parent.is_dir():
        raise ValueError("submission does not contain scripts/ for judge launcher")
    launcher_path.write_text(judge_launcher(manifest, samples), encoding="utf-8")
    launcher_path.chmod(0o755)

    result_dir = log_dir / "results"
    metadata: dict[str, Any] = {
        "repo": args.repo,
        "revision": args.revision,
        "work_dir": str(work_dir),
        "case_dir": str(case_dir),
        "checkpoint": str(checkpoint),
        "checkpoint_sha256": actual_checkpoint_sha,
        "execute_requested": args.execute,
        "launcher": str(launcher_path),
    }

    if not args.execute:
        metadata["status"] = "prepared_not_executed"
        (log_dir / "judge_result.json").write_text(
            json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print("Prepared submission and installed judge launcher; --execute was not supplied.")
        return 0

    environment = controlled_environment(work_dir, case_dir, checkpoint, result_dir,
                                         args.cuda_visible_devices)
    exit_code, elapsed_s, timed_out = run_submission(
        ["bash", "scripts/run_compute_benchmark.sh"], work_dir, environment,
        args.timeout_s, log_dir / "submission.log")
    metadata.update({
        "exit_code": exit_code,
        "external_wall_s": elapsed_s,
        "timed_out": timed_out,
    })

    try:
        if timed_out:
            raise RuntimeError(f"submission exceeded timeout ({args.timeout_s}s)")
        if exit_code != 0:
            raise RuntimeError(f"submission exited with {exit_code}")
        metadata["validation"] = validate_videos(
            result_dir, reference_dir, args.max_frame_mae, args.max_frame_error)
        metadata["status"] = "accepted"
        print(f"ACCEPTED external_wall_s={elapsed_s:.6f}")
        return_code = 0
    except Exception as error:  # Record a judge decision even on invalid output.
        metadata["status"] = "rejected"
        metadata["reason"] = str(error)
        print(f"REJECTED: {error}", file=sys.stderr)
        return_code = 1
    finally:
        (log_dir / "judge_result.json").write_text(
            json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return return_code


if __name__ == "__main__":
    raise SystemExit(main())
